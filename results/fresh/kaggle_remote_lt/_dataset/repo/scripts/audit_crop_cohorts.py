def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--from-existing", action="store_true",
                        help="Recompute analysis from existing detailed game JSON without rerunning games")
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    missing = [p for p in (BASELINE, RIVAL) if not p.exists()]
    if missing:
        raise FileNotFoundError(missing)

    details = []
    loaders = []
    if args.from_existing:
        from kaggle_environments.agent import get_last_callable
        from kaggle_environments.envs.kaggriculture import kaggriculture as engine
        baseline = get_last_callable(BASELINE.read_text(encoding="utf-8"), path=str(BASELINE))
        rival = get_last_callable(RIVAL.read_text(encoding="utf-8"), path=str(RIVAL))
        loader = {
            "baseline_callable_name": baseline.__name__,
            "baseline_callable_first_line": baseline.__code__.co_firstlineno,
            "rival_callable_name": rival.__name__,
            "rival_callable_first_line": rival.__code__.co_firstlineno,
        }
        for seed in SEEDS:
            path = args.out / f"game-{seed}.json"
            detail = json.loads(path.read_text(encoding="utf-8"))
            detail["analysis"] = _analyze_game(
                seed, detail["shops"], detail["cash"], detail["commands"],
                detail["crop_events"], detail["actions"], engine)
            detail["analysis"]["native_worker_audit"] = _native_worker_audit(
                detail["shops"], detail["actions"][0])
            path.write_text(json.dumps(_jsonable(detail), indent=2), encoding="utf-8")
            details.append(detail)
            loaders.append(loader)
            print(json.dumps({"seed": seed, "recomputed": True,
                              "counts": detail["analysis"]["counts"]}), flush=True)
    else:
        for seed in SEEDS:
            detail, loader = run_game(seed)
            details.append(detail)
            loaders.append(loader)
            (args.out / f"game-{seed}.json").write_text(
                json.dumps(_jsonable(detail), indent=2), encoding="utf-8")
            print(json.dumps({"seed": seed, "cash": detail["cash"],
                              "counts": detail["analysis"]["counts"]}), flush=True)
    assert loaders[0] == loaders[1]
    summary = _build_summary(details, loaders[0])
    (args.out / "summary.json").write_text(json.dumps(_jsonable(summary), indent=2), encoding="utf-8")
    _write_markdown(summary, args.out / "summary.md")
    print(json.dumps({"summary": str((args.out / 'summary.json').resolve()),
                      "markdown": str((args.out / 'summary.md').resolve())}), flush=True)


if __name__ == "__main__":
    main()

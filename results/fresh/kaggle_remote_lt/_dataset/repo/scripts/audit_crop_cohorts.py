def _compact_action(action):
    return " ".join(map(str, action)) if isinstance(action, list) else repr(action)


def _timeline_rows(commands, day, actor):
    rows = []
    for c in commands:
        if c["day"] != day or c["actor"] != actor:
            continue
        rows.append({
            "step": c["step"],
            "hour": c["hour"],
            "action": c["action"],
            "pre_position": c["pre_position"],
            "post_position": c["post_position"],
            "pre_inventory": c["pre_inventory"],
            "post_inventory": c["post_inventory"],
            "had_effect": c["had_effect"],
        })
    return rows


def _terminal_suffixes(commands):
    """Strict end-of-day PASS suffixes; scattered PASS is not usable slack."""
    groups = defaultdict(list)
    for c in commands:
        groups[(c["day"], c["actor"])].append(c)
    result = []
    for (day, actor), rows in sorted(groups.items()):
        rows.sort(key=lambda r: r["step"])
        suffix = []
        for row in reversed(rows):
            if row["action"] != ["PASS"]:
                break
            suffix.append(row)
        suffix.reverse()
        pass_total = sum(r["action"] == ["PASS"] for r in rows)
        if suffix:
            first = suffix[0]
            result.append({
                "day": day,
                "actor": actor,
                "actor_index": first["actor_index"],
                "terminal_passes": len(suffix),
                "all_passes": pass_total,
                "suffix_start_step": first["step"],
                "suffix_start_hour": first["hour"],
                "start_position": first["pre_position"],
                "held_inventory": first["pre_inventory"],
                "last_meaningful_step": first["step"] - 1,
            })
        else:
            last = rows[-1]
            result.append({
                "day": day,
                "actor": actor,
                "actor_index": last["actor_index"],
                "terminal_passes": 0,
                "all_passes": pass_total,
                "suffix_start_step": None,
                "suffix_start_hour": None,
                "start_position": None,
                "held_inventory": None,
                "last_meaningful_step": last["step"],
            })
    return result


def _reachable_suffixes(suffixes, cell, available_step, day, job_actions=1):
    """Workers able to reach a cell and complete all required work actions."""
    reachable = []
    day_end = day * 24 + 23
    for s in suffixes:
        if s["day"] != day or not s["terminal_passes"]:
            continue
        effective_start = max(s["suffix_start_step"], available_step)
        remaining_actions = day_end - effective_start + 1
        x, y = s["start_position"]
        distance = abs(x - cell[0]) + abs(y - cell[1])
        required = distance + job_actions
        if required <= remaining_actions:
            reachable.append({
                **s,
                "target": list(cell),
                "available_step": available_step,
                "distance": distance,
                "job_actions": job_actions,
                "required_actions_walk_plus_job": required,
                "remaining_actions_after_available": remaining_actions,
                "spare_actions_after_job": remaining_actions - required,
            })
    return sorted(reachable, key=lambda r: (-r["spare_actions_after_job"], r["actor_index"]))


def _connected_components(cells):
    pending = set(cells)
    groups = []
    while pending:
        seed = min(pending)
        pending.remove(seed)
        group = {seed}
        frontier = [seed]
        while frontier:
            x, y = frontier.pop()
            for nxt in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
                if nxt in pending:
                    pending.remove(nxt)
                    group.add(nxt)
                    frontier.append(nxt)
        groups.append(sorted(group))
    return sorted(groups, key=lambda g: (len(g), g), reverse=True)


def _analyze_game(seed, shops, rewards, commands, crop_events, actions, engine):
    own = [c for c in commands if c["seat"] == 0]
    suffixes = _terminal_suffixes(own)
    by_cell = defaultdict(list)
    for event in crop_events:
        if event["seat"] == 0:
            by_cell[tuple(event["cell"])].append(event)
    for events in by_cell.values():
        events.sort(key=lambda e: (e["step"], e["actor_index"]))

    transitions = []
    exhausted = []
    for cell, events in sorted(by_cell.items()):
        for i, event in enumerate(events):
            if event["kind"] != "HARVEST" or event["day"] < DAY_START:
                continue
            crop = event["crop"]
            crop_data = engine.CROPS[crop]
            later_plant = next((e for e in events[i + 1:] if e["kind"] == "PLANT"), None)
            if not crop_data["ongoing"] and later_plant is not None:
                row = {
                    "cell": list(cell),
                    "old_crop": crop,
                    "harvest_step": event["step"],
                    "harvest_day": event["day"],
                    "harvest_units": event["units"],
                    "replant_crop": later_plant["crop"],
                    "replant_step": later_plant["step"],
                    "replant_day": later_plant["day"],
                    "replant_actor": later_plant["actor"],
                    "replant_actor_index": later_plant["actor_index"],
                    "hours_empty": later_plant["step"] - event["step"],
                    "zero_extra_labor_command_substitution": True,
                    "native_replant_worker_timeline": _timeline_rows(
                        own, later_plant["day"], later_plant["actor"]),
                    "cell_events": events,
                }
                transitions.append(row)
            elif crop_data["ongoing"] and event.get("was_final_ongoing_harvest"):
                weed_step = int(event["tile_before"].get("max_lifespan_step", -1))
                weed_day = weed_step // 24 if 0 <= weed_step < 720 else None
                reaches = (_reachable_suffixes(
                    suffixes, cell, weed_step, weed_day, job_actions=2)
                    if weed_day is not None else [])
                exhausted.append({
                    "cell": list(cell),
                    "crop": crop,
                    "planted_day": event["tile_before"].get("planted_day"),
                    "final_harvest_step": event["step"],
                    "final_harvest_day": event["day"],
                    "final_harvest_units": event["units"],
                    "weed_step": weed_step,
                    "weed_day": weed_day,
                    "required_commands": [["DIG"], ["PLANT", "<replacement>"]],
                    "native_next_plant": later_plant,
                    "weed_day_reachable_terminal_workers": reaches,
                    "cell_events": events,
                })

    # Small spatial cohorts with the same native timing/crop transition.
    cohort_buckets = defaultdict(list)
    for row in transitions:
        key = (row["old_crop"], row["replant_crop"], row["harvest_day"], row["replant_day"])
        cohort_buckets[key].append(tuple(row["cell"]))
    cohorts = []
    for key, cells in sorted(cohort_buckets.items()):
        for component in _connected_components(cells):
            cohorts.append({
                "old_crop": key[0],
                "native_replant_crop": key[1],
                "harvest_day": key[2],
                "replant_day": key[3],
                "cells": [list(c) for c in component],
                "size": len(component),
            })

    exhausted_buckets = defaultdict(list)
    for row in exhausted:
        exhausted_buckets[(row["crop"], row["final_harvest_day"])].append(tuple(row["cell"]))
    exhausted_cohorts = []
    for key, cells in sorted(exhausted_buckets.items()):
        for component in _connected_components(cells):
            member_rows = [r for r in exhausted if tuple(r["cell"]) in set(component)]
            exhausted_cohorts.append({
                "crop": key[0],
                "final_harvest_day": key[1],
                "cells": [list(c) for c in component],
                "size": len(component),
                "reachable_actor_options": sum(bool(r["weed_day_reachable_terminal_workers"])
                                               for r in member_rows),
            })

    # Attach original full-day timelines only for actors that make a candidate
    # reachable. This keeps the summary inspectable without confusing PASS count
    # with usable slack.
    promising = []
    for row in exhausted:
            reaches = row["weed_day_reachable_terminal_workers"]
            if not reaches:
                continue
            day = row["weed_day"]
            promising.append({
                "kind": "ongoing_exhausted",
                "cell": row["cell"],
                "day": day,
                "crop": row["crop"],
                "native_replant_crop": None,
                "weed_step": row["weed_step"],
                "required_commands": row["required_commands"],
                "cell_command_timeline": [c for c in own if c["day"] == day and c["pre_position"] == row["cell"]],
                "reachable_workers": [{
                    **reach,
                    "original_daily_timeline": _timeline_rows(own, day, reach["actor"]),
                } for reach in reaches],
            })

    action_validation = []
    for seat in (0, 1):
        seat_actions = actions[seat]
        assert len(seat_actions) == 719, (seed, seat, len(seat_actions))
        assert all(isinstance(a["action"], dict) for a in seat_actions)
        action_validation.append({
            "seat": seat,
            "calls": len(seat_actions),
            "dict_actions": sum(isinstance(a["action"], dict) for a in seat_actions),
            "steps": [seat_actions[0]["step"], seat_actions[-1]["step"]],
        })

    return {
        "seed": seed,
        "shops": shops,
        "cash": rewards,
        "margin": rewards[0] - rewards[1],
        "action_validation": action_validation,
        "baseline_action_0": actions[0][0]["action"],
        "post_day12_one_time_harvest_replants": transitions,
        "post_day12_ongoing_final_harvests": exhausted,
        "one_time_spatial_cohorts": cohorts,
        "ongoing_exhausted_spatial_cohorts": exhausted_cohorts,
        "daily_terminal_suffixes": [s for s in suffixes if s["day"] >= DAY_START],
        "promising_target_timelines": promising,
        "counts": {
            "one_time_harvest_replants": len(transitions),
            "ongoing_final_harvests": len(exhausted),
            "one_time_cohorts": len(cohorts),
            "ongoing_exhausted_cohorts": len(exhausted_cohorts),
            "promising_cells_with_reachable_terminal_worker": len(promising),
            "zero_extra_labor_replant_substitutions": len(transitions),
            "raw_pass_commands_post_day12": sum(
                c["action"] == ["PASS"] for c in own if c["day"] >= DAY_START),
            "terminal_pass_commands_post_day12": sum(
                s["terminal_passes"] for s in suffixes if s["day"] >= DAY_START),
        },
    }


def _native_worker_audit(shops, actions):
    """Compare selected native tape width with real aligned worker width."""
    from kaggle_environments.agent import get_last_callable
    loaded = get_last_callable(BASELINE.read_text(encoding="utf-8"), path=str(BASELINE))
    g = loaded.__globals__
    pair = tuple(shops[:2])
    route = g["_R108_SHOP_ROUTES"].get(pair, 100) if "YARN_STORE" not in pair else g["_R110_OLD_SHOPS"].get(pair, 0)
    rows = []
    for day in range(DAY_START, 30):
        start, stop = day * 24, min(719, (day + 1) * 24)
        native_route = 2 if start >= 648 else route
        tape = g["_IMPL"].chassis.routes[native_route]
        expected = max(len(tape[t].get("hands", [])) for t in range(start, stop))
        widths = [len(actions[t]["action"].get("hands", [])) for t in range(start, stop)]
        rows.append({
            "day": day,
            "native_route": native_route,
            "native_tape_max_hands": expected,
            "observed_output_min_hands": min(widths),
            "observed_output_max_hands": max(widths),
            "extra_hands_above_native_max": max(widths) - expected,
        })
    return {
        "first_two_shops": list(pair),
        "selected_route_before_terminal": route,
        "terminal_route": 2,
        "days": rows,
        "guard": "Input-tour overlay computes expected from the selected native tape and returns unchanged unless every real hand index is either native or owned by a known overlay; hand_align pads/truncates output only to real hands.",
    }


def run_game(seed):
    from kaggle_environments import make
    from kaggle_environments.agent import get_last_callable
    from kaggle_environments.envs.kaggriculture import kaggriculture as engine

    baseline_source = BASELINE.read_text(encoding="utf-8")
    rival_source = RIVAL.read_text(encoding="utf-8")
    baseline = get_last_callable(baseline_source, path=str(BASELINE))
    rival = get_last_callable(rival_source, path=str(RIVAL))
    assert callable(baseline) and callable(rival)

    shops = random.Random(seed ^ SHOP_SALT).choices(sorted(engine.SHOPS), k=8)
    env = make("kaggriculture", configuration={"seed": seed, "episodeSteps": 720})
    original_end = engine._end_of_day
    original_apply = engine._apply_unit_action
    original_interpreter = env.interpreter
    context = {"active": False, "step": None, "seats": {}}
    commands = []
    crop_events = []
    actions = [[], []]

    def controlled_end(state, environment, day):
        original_end(state, environment, day)
        unlocked = state[0].observation.town.unlocked_shops
        unlocked[:] = shops[:len(unlocked)]

    def traced_interpreter(state, environment):
        context["active"] = True
        context["step"] = int(state[0].observation.step)
        context["seats"] = {id(f): i for i, f in enumerate(state[0].observation.farms)}
        try:
            return original_interpreter(state, environment)
        finally:
            context["active"] = False

    def traced_apply(farm, private, idx, action, *args, **kwargs):
        if not context["active"] or id(farm) not in context["seats"]:
            return original_apply(farm, private, idx, action, *args, **kwargs)
        seat = context["seats"][id(farm)]
        step = context["step"]
        pos0 = engine._farmer_position(farm, idx)
        inv0 = deepcopy(private["inventories"][idx]) if idx < len(private["inventories"]) else {}
        seeds0 = deepcopy(private["seeds"])
        tile0 = deepcopy(farm["tiles"][pos0[1]][pos0[0]]) if pos0 is not None else None
        result = original_apply(farm, private, idx, action, *args, **kwargs)
        pos1 = engine._farmer_position(farm, idx)
        inv1 = deepcopy(private["inventories"][idx]) if idx < len(private["inventories"]) else {}
        tile1 = deepcopy(farm["tiles"][pos1[1]][pos1[0]]) if pos1 is not None else None
        seeds1 = deepcopy(private["seeds"])
        changed = pos0 != pos1 or inv0 != inv1 or tile0 != tile1 or seeds0 != seeds1
        row = {
            "seat": seat,
            "step": step,
            "day": step // 24,
            "hour": step % 24,
            "actor": "farmer" if idx == 0 else f"hand_{idx}",
            "actor_index": idx,
            "action": deepcopy(action),
            "pre_position": list(pos0) if pos0 is not None else None,
            "post_position": list(pos1) if pos1 is not None else None,
            "pre_inventory": inv0,
            "post_inventory": inv1,
            "inventory_delta": _inventory_delta(inv0, inv1),
            "had_effect": changed,
        }
        commands.append(row)
        op = action[0] if isinstance(action, list) and action else None
        if changed and op == "PLANT" and isinstance(tile1, dict) and tile1.get("kind") == "PLANT":
            crop_events.append({
                "kind": "PLANT", "seat": seat, "step": step, "day": step // 24,
                "hour": step % 24, "actor": row["actor"], "actor_index": idx,
                "cell": list(pos0), "crop": tile1["crop"], "tile_after": tile1,
            })
        if changed and op == "HARVEST" and isinstance(tile0, dict) and tile0.get("kind") == "PLANT":
            crop = tile0["crop"]
            units = max(0, inv1.get(crop, 0) - inv0.get(crop, 0))
            if units:
                crop_events.append({
                    "kind": "HARVEST", "seat": seat, "step": step, "day": step // 24,
                    "hour": step % 24, "actor": row["actor"], "actor_index": idx,
                    "cell": list(pos0), "crop": crop, "units": units,
                    "tile_before": tile0, "tile_after": tile1,
                    "was_final_ongoing_harvest": bool(
                        engine.CROPS[crop]["ongoing"] and tile0.get("max_lifespan_step", -1) >= 0),
                })
        return result

    def wrapped(agent, seat):
        def call(obs, configuration=None):
            action = agent(obs, configuration)
            actions[seat].append({"step": int(obs["step"]), "action": deepcopy(action)})
            if not isinstance(action, dict):
                raise AssertionError(f"seed {seed} seat {seat} step {obs['step']}: non-dict action")
            return action
        return call

    engine._end_of_day = controlled_end
    engine._apply_unit_action = traced_apply
    env.interpreter = traced_interpreter
    started = time.perf_counter()
    try:
        env.run([wrapped(baseline, 0), wrapped(rival, 1)])
    finally:
        engine._end_of_day = original_end
        engine._apply_unit_action = original_apply
        env.interpreter = original_interpreter
    elapsed = time.perf_counter() - started
    assert len(env.steps) == 720, (seed, len(env.steps), env.logs[-3:])
    assert all(s.status in ("ACTIVE", "DONE") for states in env.steps for s in states)
    assert all(s.status == "DONE" for s in env.state)
    rewards = [s.reward for s in env.state]
    analysis = _analyze_game(seed, shops, rewards, commands, crop_events, actions, engine)
    analysis["native_worker_audit"] = _native_worker_audit(shops, actions[0])
    detail = {
        "design": "Official engine; corrected baseline seat 0 vs downloaded public V45 seat 1; hidden common controlled shops.",
        "seed": seed,
        "elapsed_seconds": elapsed,
        "shops": shops,
        "cash": rewards,
        "actions": actions,
        "commands": commands,
        "crop_events": crop_events,
        "analysis": analysis,
    }
    loader = {
        "baseline_callable_name": baseline.__name__,
        "baseline_callable_first_line": baseline.__code__.co_firstlineno,
        "rival_callable_name": rival.__name__,
        "rival_callable_first_line": rival.__code__.co_firstlineno,
    }
    return detail, loader


def _build_summary(details, loader):
    games = [d["analysis"] for d in details]
    recurring = Counter()
    exhausted = Counter()
    for game in games:
        for row in game["post_day12_one_time_harvest_replants"]:
            recurring[(row["old_crop"], row["replant_crop"])] += 1
        for row in game["post_day12_ongoing_final_harvests"]:
            exhausted[row["crop"]] += 1

    targets = []
    for game in games:
        for row in game["promising_target_timelines"]:
            best = row["reachable_workers"][0]
            targets.append({
                "seed": game["seed"], "kind": row["kind"], "cell": row["cell"],
                "day": row["day"], "crop": row["crop"],
                "native_replant_crop": row["native_replant_crop"],
                "best_worker": best["actor"], "terminal_passes": best["terminal_passes"],
                "start_position": best["start_position"], "held_inventory": best["held_inventory"],
                "distance": best["distance"], "spare_actions_after_job": best["spare_actions_after_job"],
                "season_viable_crop_harvest": best["day"] + 2 <= 29,
            })
    targets.sort(key=lambda r: (-r["spare_actions_after_job"], r["seed"], r["day"], r["cell"]))

    cohort_maps = []
    for game in games:
        current = {}
        for c in game["one_time_spatial_cohorts"]:
            key = (c["old_crop"], c["native_replant_crop"], c["harvest_day"],
                   c["replant_day"], tuple(tuple(x) for x in c["cells"]))
            current[key] = c
        cohort_maps.append(current)
    common = set(cohort_maps[0]) & set(cohort_maps[1])
    stable_small = []
    for key in sorted(common, key=lambda k: (k[2], -len(k[4]), k[4])):
        c = cohort_maps[0][key]
        if c["old_crop"] == "WHEAT" and c["native_replant_crop"] == "WHEAT" and c["size"] <= 3 and c["replant_day"] <= 24:
            stable_small.append({**c, "seen_in_both_seeds": True,
                                 "mechanical_change": "Replace the existing native PLANT WHEAT command(s); no extra planting action or worker."})
    stable_small = stable_small[:12]

    return {
        "scope": {
            "games": 2,
            "seeds": list(SEEDS),
            "baseline_seat": 0,
            "opponent": "downloaded public V45",
            "controlled_shops": "independent Random(seed ^ 0xA171), uniform with replacement; revealed only on native unlock days",
            "post_day_start": DAY_START,
        },
        "sources": {
            "baseline": str(BASELINE), "baseline_sha256": sha256(BASELINE.read_bytes()).hexdigest(),
            "rival": str(RIVAL), "rival_sha256": sha256(RIVAL.read_bytes()).hexdigest(),
            "script": str(Path(__file__).resolve()), "loader": loader,
        },
        "validation": {
            "official_engine_complete_states_each": 720,
            "all_action_calls_checked": sum(v["calls"] for g in games for v in g["action_validation"]),
            "baseline_action_calls_checked": sum(g["action_validation"][0]["calls"] for g in games),
            "all_actions_are_dicts": all(v["calls"] == v["dict_actions"] for g in games for v in g["action_validation"]),
            "corrected_opening_feed_seen_both_games": all(g["baseline_action_0"].get("market") == [["BUY_PRODUCT", "WHEAT", 5]] for g in games),
        },
        "games": [{k: g[k] for k in ("seed", "shops", "cash", "margin", "action_validation", "counts")}
                  for g in games],
        "native_crop_transitions": {
            "one_time_harvest_then_replant_counts": {f"{a}->{b}": n for (a, b), n in sorted(recurring.items())},
            "ongoing_final_harvest_counts": dict(sorted(exhausted.items())),
            "stable_small_zero_extra_labor_cohorts": stable_small,
        },
        "native_worker_widths": [{"seed": g["seed"], **g["native_worker_audit"]} for g in games],
        "worker_slack_definition": "Only the uninterrupted terminal PASS suffix after an actor's final non-PASS command. An exhausted ongoing plot becomes usable only at max_lifespan_step and requires distance + DIG + PLANT to fit after that weed step.",
        "worker_slack_result": "All mechanically reachable exhausted-strawberry options occur on day 28. Even WHEAT/CARROT need two days to first yield, so none can harvest before the day-29 season end; options sharing hand_7's five-action suffix are mutually exclusive.",
        "promising_target_cells": targets,
        "caveat": "One-time crop substitutions reuse an existing native PLANT command, but that proves only planting feasibility. Exhausted ongoing replacements require a real weed-step DIG+PLANT window. Seed inventory, future watering/harvest/transport, prices, and route disruption still require a policy experiment.",
    }


